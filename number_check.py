
answer = "да"

while answer == "да":  # повторяем, пока пользователь отвечает "да"
    text = input("Введите число: ")  # читаем число как текст

    try:  # пробуем превратить текст в целое число
        n = int(text)  # если ввели не число, здесь возникнет ошибка ValueError
    except ValueError:  # ошибка неправильного ввода
        print("Ошибка: нужно ввести целое число")  # сообщаем пользователю
        continue  # возвращаемся к началу цикла и просим ввести число снова

    if n > 0:
        sign = "Положительное: да"
    elif n < 0:
        sign = "Отрицательное: да"
    else:  # иначе это ноль
        sign = "Ноль: да"
    print("Ваше число:", n)
    print(sign)

    print("Четное:", "да" if n % 2 == 0 else "нет")  # четное, если остаток от деления на 2 равен 0
    print("Делится на 3:", "да" if n % 3 == 0 else "нет")  # проверка деления на 3
    print("Делится на 5:", "да" if n % 5 == 0 else "нет")  # проверка деления на 5

    prime = n > 1  # простые числа только больше 1
    for i in range(2, n):  # перебираем возможные делители от 2 до n-1
        if n % i == 0:  # если нашелся делитель
            prime = False  # число не простое
            break
    print("Простое:", "да" if prime else "нет")

    print("Количество цифр:", len(str(abs(n))))  # длина строки без минуса = количество цифр

    answer = input("Проверить ещё одно число? (да/нет): ")
print("Работа программы завершена.")